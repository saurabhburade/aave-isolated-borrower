const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const base = process.env.APP_URL || 'http://127.0.0.1:3210';
const usdc = '0xA0b86991c6218b36c1d19D4a2e9Eb0cE3606eB48';
const weth = '0xC02aaA39b223FE8D0A0e5C4F27eAD9083C756Cc2';
const dai = '0x6B175474E89094C44Da98b954EedeAC495271d0F';
const reserve = (address, symbol, decimals, usdPrice, canBorrow = true) => ({ address, symbol, name: symbol, decimals, usdPrice, canBorrow, canSupply: true, canCollateral: true, maxLtv: '0.75', liquidationThreshold: '0.8' });
const markets = [
  { id: 'v3', version: 3, venue: '0x0000000000000000000000000000000000000001', name: 'Aave V3 Ethereum', reserves: [reserve(usdc, 'USDC', 6, '0.9998'), reserve(weth, 'WETH', 18, '3000'), reserve(dai, 'DAI', 18, '1')] },
  { id: 'v4', version: 4, venue: '0x0000000000000000000000000000000000000002', name: 'Aave V4 Main', reserves: [reserve(usdc, 'USDC', 6, '0.9998'), reserve(weth, 'WETH', 18, '3000')] },
  { id: 'incompatible', version: 4, venue: '0x0000000000000000000000000000000000000003', name: 'Aave V4 DAI only', reserves: [reserve(usdc, 'USDC', 6, '0.9998'), reserve(dai, 'DAI', 18, '1')] },
].map(m => ({ ...m, chainId: 1, network: 'Ethereum', isTestnet: false }));
let browser;
(async () => {
  browser = await chromium.launch({ headless: true, chromiumSandbox: true, ...(process.env.HEADLESS_CHROMIUM ? { executablePath: process.env.HEADLESS_CHROMIUM } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors = [];
  const requests = [];
  let releaseCatalog, releaseRates;
  const catalogReady = new Promise(resolve => { releaseCatalog = resolve; });
  const ratesReady = new Promise(resolve => { releaseRates = resolve; });
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/api/markets?**', route => route.fulfill({ json: { markets: [], assets: [], freshness: { status: 'unavailable', observedAt: null, blockNumber: null } } }));
  await page.route('**/api/market-catalog?**', async route => { await catalogReady; await route.fulfill({ json: { markets, errors: [] } }); });
  await page.route('**/api/market-rates?**', async route => {
    await ratesReady;
    const url = new URL(route.request().url());
    const ids = JSON.parse(url.searchParams.get('marketIds'));
    requests.push(ids);
    await route.fulfill({ json: { rates: ids.map(marketId => ({ marketId, borrowApy: marketId === 'v4' ? '0.03' : marketId === 'incompatible' ? '0.01' : '0.05', observedAt: new Date().toISOString() })), errors: [] } });
  });
  await page.route('**/api/rate-history?**', route => route.fulfill({ json: { series: [], errors: [] } }));
  await page.goto(`${base}/31337`);
  await page.getByRole('status', { name: 'Loading market', exact: true }).first().waitFor();
  assert.equal(await page.getByRole('status', { name: 'Loading market', exact: true }).count(), await page.locator('.platform-table tbody tr').count(), 'each loading row exposes its loading state');
  await page.locator('.platform-table').screenshot({ path: '/tmp/aave-market-catalog-skeleton.png' });
  releaseCatalog();
  await page.getByRole('status', { name: 'Loading borrow APY', exact: true }).first().waitFor();
  assert.equal(await page.getByText('Loading…', { exact: true }).count(), 0);
  await page.locator('.platform-table').screenshot({ path: '/tmp/aave-market-rate-skeleton.png' });
  releaseRates();
  const rows = page.locator('.platform-table tbody tr');
  await page.locator('.platform-table tr[data-selected=true]').filter({ hasText: 'Main' }).waitFor();
  assert.equal(await rows.count(), 2, 'unsupported collateral market is filtered out');
  assert.match(await rows.first().innerText(), /Main/);
  assert.deepEqual(requests.at(-1), ['v3', 'v4']);
  assert.equal(await page.locator('#borrow-health-factor-error').count(), 0, 'missing amounts do not trigger a low-health error');
  assert.equal(await page.locator('.market-chain-badge[aria-label="Ethereum network"]').count(), 2);
  assert.equal(await page.locator('.platform-table').getByText('Est.', { exact: true }).count(), 0);
  assert.equal(await page.locator('.platform-name small').filter({ hasText: '· Ethereum' }).count(), 0);
  await page.getByRole('textbox', { name: 'Debt amount', exact: true }).fill('6');
  await page.getByRole('textbox', { name: 'Collateral amount 1', exact: true }).fill('2');
  await page.getByText('$6.00', { exact: true }).waitFor();
  await page.getByText('$6,000.00', { exact: true }).waitFor();
  await page.locator('.platform-table tbody tr').first().getByText('800.16', { exact: true }).waitFor();
  assert.equal(await page.locator('.platform-table').getByText('75.00%', { exact: true }).count(), 2);
  await page.locator('.position-preview').getByText('0.10%', { exact: true }).waitFor();
  assert.equal(await page.getByText('Aave markets', { exact: true }).count(), 0);
  const healthError = page.getByRole('alert').filter({ hasText: 'Health factor too low to proceed.' });
  const connect = page.getByRole('region', { name: 'Borrow widget' }).getByRole('button', { name: 'Connect wallet', exact: true });
  await page.getByRole('textbox', { name: 'Debt amount', exact: true }).fill('20000');
  await healthError.waitFor();
  assert.equal(await connect.isDisabled(), true, 'low health factor blocks proceeding before connecting');
  await page.getByRole('textbox', { name: 'Debt amount', exact: true }).fill(String(4800 / 1.04999 / 0.9998));
  await healthError.waitFor();
  assert.equal(await connect.isDisabled(), true, 'unrounded health factor below 1.05 remains blocked');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.getByRole('textbox', { name: 'Debt amount', exact: true }).fill(String(4800 / 1.05001 / 0.9998));
  await healthError.waitFor({ state: 'detached' });
  assert.equal(await connect.isDisabled(), false, 'correcting the amount clears the error and enables proceeding');
  await page.getByRole('textbox', { name: 'Debt amount', exact: true }).fill('20000');
  await healthError.waitFor();
  await page.locator('#borrow-health-factor-error').evaluate(element => Promise.all(element.getAnimations({ subtree: true }).map(animation => animation.finished)));
  await page.locator('.borrow-column').screenshot({ path: '/tmp/aave-health-factor-error.png' });
  await page.getByRole('textbox', { name: 'Debt amount', exact: true }).fill('');
  await healthError.waitFor({ state: 'detached' });
  assert.equal(await connect.isDisabled(), false, 'empty amounts do not produce a low-health error');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.locator('.platform-table').screenshot({ path: '/tmp/aave-market-chain-badges.png' });
  await page.getByRole('button', { name: 'Aave V3 Ethereum', exact: true }).click();
  await page.getByRole('textbox', { name: 'Debt amount', exact: true }).fill('8');
  assert.match(await page.locator('.platform-table tr[data-selected=true]').innerText(), /V3/);
  await page.getByRole('button', { name: 'V4', exact: true }).click();
  await page.locator('.platform-table tr[data-selected=true]').filter({ hasText: 'Main' }).waitFor();
  assert.deepEqual(requests.at(-1), ['v4']);
  await page.getByRole('button', { name: 'All', exact: true }).click();
  await page.locator('.platform-table tr[data-selected=true]').filter({ hasText: 'Main' }).waitFor();
  await page.getByRole('button', { name: 'Add asset', exact: true }).click();
  await page.locator('.platform-table tr[data-selected=true]').filter({ hasText: 'V3' }).waitFor();
  assert.equal(await rows.count(), 1, 'every collateral must be supported by the same market');
  assert.deepEqual(requests.at(-1), ['v3']);
  await page.getByRole('button', { name: 'V4', exact: true }).click();
  await page.locator('.platform-table').getByText('No markets support this asset and collateral combination.').waitFor();
  assert.equal(await page.locator('.platform-table tr[data-selected=true]').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Passed: API-only browsing, filtered rate requests, lowest default, manual choice, version filter, multi-collateral support, USD values, risk estimates, and catalog/rate skeletons.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); });
